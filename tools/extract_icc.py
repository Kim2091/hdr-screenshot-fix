"""Extract the iCCP profile from a PNG and write it, unmodified, as a C++ header.

usage: python -I extract_icc.py source.png rec2100pq_icc.h
Prints the profile's desc and cprt tags so the licence statement can be checked.
"""
import hashlib
import struct
import sys
import zlib

src, dst = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read()
assert data[:8] == b'\x89PNG\r\n\x1a\n'
pos, prof, name = 8, None, None
while pos < len(data):
    n, = struct.unpack('>I', data[pos:pos + 4])
    typ, body = data[pos + 4:pos + 8], data[pos + 8:pos + 8 + n]
    assert zlib.crc32(typ + body) & 0xffffffff == struct.unpack('>I', data[pos + 8 + n:pos + 12 + n])[0]
    if typ == b'iCCP':
        name, rest = body.split(b'\0', 1)
        assert rest[0] == 0
        prof = zlib.decompress(rest[1:])
    pos += 12 + n
assert prof is not None, 'no iCCP chunk'


def tag_text(sig):
    cnt, = struct.unpack('>I', prof[128:132])
    for i in range(cnt):
        s, off, ln = struct.unpack('>4sII', prof[132 + 12 * i:144 + 12 * i])
        if s == sig:
            t = prof[off:off + ln]
            if t[:4] == b'mluc':
                n_, rs = struct.unpack('>II', t[8:16])
                l, o = struct.unpack('>II', t[20:28])
                return t[o:o + l].decode('utf-16-be')
            return t[8:].split(b'\0')[0].decode('latin-1')
    return None


print(f'iCCP name: {name.decode("latin-1")}, profile {len(prof)} bytes, sha256 {hashlib.sha256(prof).hexdigest()}')
print(f'desc: {tag_text(b"desc")!r}')
print(f'cprt: {tag_text(b"cprt")!r}')

lines = [
    '// Generated by tools/extract_icc.py. Do not edit.',
    '// PQ ICC profile (desc RGB_D65_202_Rel_PeQ) as embedded by the NVIDIA app in its HDR PNG',
    '// screenshots, libjxl-style. The profile\'s copyright tag states CC0. Included unmodified.',
    f'// SHA-256: {hashlib.sha256(prof).hexdigest()}',
    '#pragma once',
    '#include <cstdint>',
    '',
    f'static const uint8_t kRec2100PqIcc[{len(prof)}] = {{',
]
for i in range(0, len(prof), 16):
    lines.append('    ' + ', '.join(f'0x{b:02x}' for b in prof[i:i + 16]) + ',')
lines.append('};')
open(dst, 'w', newline='\n').write('\n'.join(lines) + '\n')
print(f'wrote {dst}')
